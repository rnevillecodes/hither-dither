// Generates the app icon SVGs from one set of shapes:
//   src-tauri/icons/app-icon.svg  full-colour source for `tauri icon`
//   src/assets/logo-shadow.svg    single-colour imprint of the waveform for the empty screen
// Usage: node scripts/gen-icons.mjs, then `npx tauri icon src-tauri/icons/app-icon.svg`.
import { writeFileSync } from "node:fs";
const C = 512; // centre
const BAR_W = 76;
const GAP = 40;
// Half-heights of the 7 bars (bar spans C-h .. C+h).
const HALF = [150, 260, 345, 235, 300, 195, 125];
const n = HALF.length;
const x0 = C - (n * BAR_W + (n - 1) * GAP) / 2;

// 4x4 Bayer matrix, normalised to 0..1 thresholds.
const BAYER = [
  [0, 8, 2, 10],
  [12, 4, 14, 6],
  [3, 11, 1, 9],
  [15, 7, 13, 5],
].map((r) => r.map((v) => (v + 0.5) / 16));

const DOT = 26;
const PITCH = 38; // dot grid pitch (2 columns per bar)

let solid = "";
let dots = "";
for (let i = 0; i < n; i++) {
  const x = x0 + i * (BAR_W + GAP);
  const h = HALF[i];
  // Bars from index 4 on dissolve into dither dots towards their tips; the core stays solid.
  const dither = i >= 4;
  const core = dither ? h * (0.62 - (i - 4) * 0.12) : h;
  solid += `<rect x="${x}" y="${C - core}" width="${BAR_W}" height="${core * 2}" rx="${BAR_W / 2}"/>`;
  if (!dither) continue;
  // Dots from the core edge out to the bar's full extent, sparser with distance.
  for (let row = 0; ; row++) {
    const d = core + PITCH * 0.75 + row * PITCH; // distance from centre, clear of the cap
    if (d > h + PITCH * 0.6) break;
    const t = (d - core) / (h - core + PITCH * 1.5); // 0 at core, ~1 past the tip
    const density = 0.95 - 0.85 * Math.min(1, t);
    for (const side of [-1, 1]) {
      for (let col = 0; col < 2; col++) {
        const threshold = BAYER[(row + (side > 0 ? 0 : 2)) % 4][(col + i) % 4];
        if (density <= threshold) continue;
        const cx = x + BAR_W / 2 + (col - 0.5) * PITCH;
        const cy = C + side * d;
        dots += `<rect x="${(cx - DOT / 2).toFixed(1)}" y="${(cy - DOT / 2).toFixed(1)}" width="${DOT}" height="${DOT}" rx="5"/>`;
      }
    }
  }
}

const xL = x0;
const xR = x0 + n * BAR_W + (n - 1) * GAP;
const TILE = `x="40" y="40" width="944" height="944" rx="210"`;

const colour = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <!-- hither-dither app icon: waveform bars dissolving into ordered-dither dots. Source for tauri icon. -->
  <defs>
    <linearGradient id="tile" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#2b2f7a"/>
      <stop offset="1" stop-color="#0e1330"/>
    </linearGradient>
    <linearGradient id="wave" gradientUnits="userSpaceOnUse" x1="${xL}" y1="0" x2="${xR}" y2="0">
      <stop offset="0" stop-color="#2fd3c9"/>
      <stop offset="0.55" stop-color="#7fd98a"/>
      <stop offset="1" stop-color="#ffc23a"/>
    </linearGradient>
  </defs>
  <rect ${TILE} fill="url(#tile)"/>
  <rect x="44" y="44" width="936" height="936" rx="206" fill="none" stroke="#ffffff" stroke-opacity="0.14" stroke-width="8"/>
  <g fill="url(#wave)">${solid}</g>
  <g fill="url(#wave)">${dots}</g>
</svg>
`;

// Just the icon's details (bars and dither dots), no tile, in one opaque colour (used as a
// CSS mask). Cropped to the waveform so it fills the element it is drawn into.
const top = C - Math.max(...HALF);
const shadow = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${xL} ${top} ${xR - xL} ${(C - top) * 2}">
  <!-- hither-dither icon imprint (shadow variant). Generated by scripts/gen-icons.mjs. -->
  <g fill="#000">${solid}${dots}</g>
</svg>
`;

const root = new URL("..", import.meta.url);
for (const [path, svg] of [
  ["src-tauri/icons/app-icon.svg", colour],
  ["src/assets/logo-shadow.svg", shadow],
]) {
  writeFileSync(new URL(path, root), svg);
  console.log(`wrote ${path}`);
}
